"""Жасушалық биология, 5-файл (митохондрия, энергия алмасуы): parse_botany1.py (QNIDS=1 STOPNID=2) шығысы → parse_ubt форматы.
Қолданылуы: python3 -I fix_cell_mito.py in.json imgdir repo out.json"""
import json, sys, os, shutil
src, imgdir, repo, dst = sys.argv[1:5]
TID = "cell-5"
KEL = ["Р. А. Келликер", "Р. Альтман"]
# «Р. А. Келликер» ішіндегі «А.» әрпі нұсқа болып бөлініп кеткен: (нұсқалар, дұрыс индекс)
FIX = {3: (["Р. А. Келликер", "Р. Альтман", "К. Бенда", "Де Дюв"], [2]),
       4: (["Р. А. Келликер", "Р. Альтман", "К. Бенданың", "Де Дюв"], [0]),
       5: (["Р. А. Келликер", "Р. Альтман", "К. Бенда", "Де Дюв"], [1]),
       # нұсқалары суретте (қолжазба формулалар), файлда дұрыс жауабы белгіленбеген — биология бойынша қойылды
       33: (["Суреттегі A", "Суреттегі B", "Суреттегі C", "Суреттегі D"], [1]),   # C6H12O6 → 2C3H4O3 + 4H + 2АТФ
       36: (["Суреттегі A", "Суреттегі B", "Суреттегі C", "Суреттегі D"], [2])}   # ... + 2НАД + 2АДФ + 2H3PO4 → 2C3H4O3 + 2НАДН2 + 2АТФ + 2H2O
TEXT = {"Митохондрия\" атауын": "«Митохондрия» атауын", "\"саркосома\"": "«саркосома»", "\"биопласт\"": "«биопласт»",
        "көбею түрінді": "көбею түрінде", "АТФ тің": "АТФ-тің", "циклынан": "циклінен", "КОА": "КоА", "АТФті": "АТФ-ті", "3NADH": "3 НАДН",
        "2Ацетил": "2 Ацетил", "АТФ, 4Н,2СО2": "АТФ, 4Н, 2СО2", "АТФ,2Н, 4СО2": "АТФ, 2Н, 4СО2", "АТФ,6Н,2СО2": "АТФ, 6Н, 2СО2", "АТФ,6Н,4СО2": "АТФ, 6Н, 4СО2",
        "36АТФ": "36 АТФ", "38АТФ": "38 АТФ", "4ФАДН2": "4 ФАДН2", "Тотығу- тотықсыздану": "Тотығу-тотықсыздану"}
def tx(s):
    for a, b in TEXT.items(): s = s.replace(a, b)
    return s
os.makedirs(f"{repo}/img/chapters/{TID}", exist_ok=True)
out = []
for q in json.load(open(src)):
    n = q["n"]
    if q["q"].startswith("Сәйкестендір"):  # файлдың соңындағы сәйкестендіру — элементтері бөлек тізімде
        out.append({"n": n, "q": "Сәйкестендір", "items": [{"text": "Анаэробты жаттығу", "answer": 0}, {"text": "Аэробты жаттығу", "answer": 2}],
                    "opts": [{"t": t, "c": False} for t in ["Штанга көтеру, ядро лақтыру", "Спринт, футбол", "Жүзу, теннис", "Алыс қашықтыққа жүгіру, велоспорт"]]})
        continue
    opts = [{"t": tx(o["t"]), "c": o["c"]} for o in q["opts"]]
    if n in FIX: o, c = FIX[n]; opts = [{"t": t, "c": i in c} for i, t in enumerate(o)]
    e = {"n": n, "q": tx(q["q"]), "opts": opts, "items": []}
    if q.get("img"):
        e["img"] = []
        for f in q["img"]:
            shutil.copy(os.path.join(imgdir, f), f"{repo}/img/chapters/{TID}/{f}"); e["img"].append(f"img/chapters/{TID}/{f}")
    out.append(e)
json.dump({"title": "", "questions": out}, open(dst, "w"), ensure_ascii=False, indent=1)
print(len(out))
