def fix(t):
    for a, b in FIX: t = t.replace(a, b)
    return re.sub(r"(?m)^(\d)\.(?=\S)", r"\1. ", t)

rows = json.load(open(sys.argv[1], encoding="utf-8"))
imgdir, repo = sys.argv[2], sys.argv[3]
os.makedirs(os.path.join(repo, "img/realubt"), exist_ok=True)
out = []
for i, r in enumerate(rows):
    q = re.sub(r"^\s*\d+\s*\.\s*", "", r["q"]).strip()
    q = re.sub(r"\s{2,}", " · ", q)
    a = "\n".join(l.rstrip() for l in r["a"].strip().split("\n"))
    a = re.sub(r"\n{3,}", "\n\n", a)
    it = {"q": fix(q), "a": fix(a)}
    if r["imgs"]:
        it["img"] = []
        for f in r["imgs"]:
            shutil.copy(os.path.join(imgdir, f), os.path.join(repo, "img/realubt", f))
            it["img"].append("img/realubt/" + f)
    if i in K:
        kq, k = K[i]
        if kq: it["kq"] = kq
        it["k"] = k
    out.append(it)
for d in range(0, len(out), 20):
    n = sum(1 for x in out[d:d + 20] if "k" in x)
    print("күн", d // 20 + 1, "сұрақ", len(out[d:d + 20]), "тест", n)
