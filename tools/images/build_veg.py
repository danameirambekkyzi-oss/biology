# ---------------- PDF-тегі қалған суреттер (2026-11-12) ----------------
# Әр тапсырма: (id, файл, тарау, атауы, crop(x0,y0,x1,y1), pad(оң, асты), scale, clean, [(жауап, бокс)], [тек жабылатын]), бокстар — бастапқы сурет координатасымен
def clean_scan(im, soft=False):  # сканерлегенде бет арқасынан көрінген сұр әріптерді ағарту (түсті суретке тимейді)
    hsv = im.convert("HSV"); px = hsv.load(); out = im.copy(); po = out.load()
    for y in range(im.height):
        for x in range(im.width):
            h, s, v = px[x, y]
            if (s < 22 and v > 200) if soft else (s < 38 and v > 150): po[x, y] = (255, 255, 255)
    return out

def build(spec):
    tid, f, mod, title, crop, pad, k, cln, Z, M = spec
    im = Image.open(f"{src}/{f}.png").convert("RGB")
    x0, y0, x1, y1 = crop; im = im.crop(crop)
