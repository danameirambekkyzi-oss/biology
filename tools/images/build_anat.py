"""«Суретпен жұмыс» → Анатомия (мұғалім жіберген PDF, 53 сурет) + барлық тапсырмаларды «папкаларға» топтау.
Қолданылуы: python3 -I build_anat.py src repo   (src — PDF-тен шыққан i-000.png … i-052.png)
Әр тапсырма: (id, файл, папка, атауы, crop, pad(оң, асты), scale, clean, [(жауап, бокс[, тігінен])], [тек жабылатын]).
Бокстар — бастапқы сурет координатасымен; нөмірлі суреттерде ұяшықтар бос орынға (pad) нөмір ретімен қойылады."""
import json, sys
from PIL import Image, ImageDraw, ImageFilter
src, repo = sys.argv[1:3]

def clean_scan(im, soft=False):
    hsv = im.convert("HSV"); px = hsv.load(); out = im.copy(); po = out.load()
    for y in range(im.height):
        for x in range(im.width):
            h, s, v = px[x, y]
            if (s < 22 and v > 200) if soft else (s < 38 and v > 150): po[x, y] = (255, 255, 255)
    return out

def build(spec):
    tid, f, folder, title, crop, pad, k, cln, Z, M = spec
    im = Image.open(f"{src}/{f}.png").convert("RGB")
    x0, y0, x1, y1 = crop; im = im.crop(crop)
    if cln: im = clean_scan(im, cln == "soft")
    W, H = im.width + pad[0], im.height + pad[1]
    S = Image.new("RGB", (W, H), "white"); S.paste(im, (0, 0)); d = ImageDraw.Draw(S)
    for b in [z[1] for z in Z] + M: d.rectangle((b[0] - x0 - 2, b[1] - y0 - 2, b[2] - x0 + 2, b[3] - y0 + 2), fill="white")
    S = S.resize((round(W * k), round(H * k)), Image.LANCZOS)
    if k > 1.2: S = S.filter(ImageFilter.UnsharpMask(radius=2, percent=90, threshold=3))
    S.save(f"{repo}/img/images/a-{tid}.jpg", quality=88)
    opts, zones = [], []
    for z in Z:
        ans, b = z[0], z[1]; opts.append(ans)
        zx, zy, zw, zh = b[0] - x0 - 1, b[1] - y0 - 1, b[2] - b[0] + 2, b[3] - b[1] + 2
        o = {"x": round(zx / W * 100, 2), "y": round(zy / H * 100, 2), "w": round(zw / W * 100, 2), "h": round(zh / H * 100, 2), "answer": len(opts) - 1}
        if len(z) > 2 and z[2]: o["v"] = True
        zones.append(o)
    return {"id": "img-a-" + tid, "module": "anatomy", "folder": folder, "title": title, "img": [f"img/images/a-{tid}.jpg"], "options": opts, "zones": zones}

def col(x, y, w, h, gap, names):
    return [(n, (x, y + i * (h + gap), x + w, y + i * (h + gap) + h)) for i, n in enumerate(names)]
def grid(x, y, w, h, gx, gy, cols, names):
    return [(n, (x + (i % cols) * (w + gx), y + (i // cols) * (h + gy), x + (i % cols) * (w + gx) + w, y + (i // cols) * (h + gy) + h)) for i, n in enumerate(names)]

